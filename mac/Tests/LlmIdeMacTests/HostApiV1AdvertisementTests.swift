import Testing
import Foundation
@testable import LlmIdeMacLib

/// Plan 6 Task 5: the QR and Bonjour TXT advertise the exact v1 TLS port and fingerprint (never the
/// dev plaintext listener), and Reset security identity revokes every v1 device but no v2 one.
@Suite("HostApiV1Advertisement", .serialized)
@MainActor
struct HostApiV1AdvertisementTests {
    /// Never the real Application Support audit file.
    private func tempAudit() -> HostApiV1AuditLog {
        HostApiV1AuditLog(fileURL: FileManager.default.temporaryDirectory.appendingPathComponent("h1-adv-audit-\(UUID().uuidString).jsonl"))
    }

    private func tempStore() -> MobilePairedDeviceStore {
        MobilePairedDeviceStore(fileURL: FileManager.default.temporaryDirectory
            .appendingPathComponent("h1-adv-\(UUID().uuidString)", isDirectory: true)
            .appendingPathComponent("devices.json"))
    }

    @Test("TXT without TLS advertises only v2")
    func txtPlain() {
        #expect(MobileControlManager.hostApiTXT(port: nil, fingerprint: nil) == ["api": "2"])
        #expect(MobileControlManager.hostApiTXT(port: 3017, fingerprint: nil) == ["api": "2"], "dev plaintext is never advertised")
    }

    @Test("TXT with TLS advertises the exact port and fingerprint, each value under 255 bytes")
    func txtTLS() {
        let fp = "sha256:" + String(repeating: "A", count: 43)
        let txt = MobileControlManager.hostApiTXT(port: 3017, fingerprint: fp)
        #expect(txt == ["api": "1,2", "h1port": "3017", "h1fp": fp])
        #expect(!NetService.data(fromTXTRecord: txt.mapValues { Data($0.utf8) }).isEmpty)
        for (k, v) in txt { #expect(k.utf8.count + 1 + v.utf8.count < 255) }
    }

    @Test("the QR keeps ip/port/pin first and adds h1port/h1fp/api only with both v1 values")
    func qr() throws {
        let with = try #require(MobileConnectionInfo.qrPayload(host: "192.168.1.20", port: 3006, pin: "123456",
                                                               hostApiPort: 3017, hostApiFingerprint: "sha256:abc"))
        let items = try #require(URLComponents(string: with)?.queryItems)
        #expect(items.prefix(3).map(\.name) == ["ip", "port", "pin"])
        let v = Dictionary(uniqueKeysWithValues: items.map { ($0.name, $0.value ?? "") })
        #expect(v["ip"] == "192.168.1.20" && v["port"] == "3006" && v["pin"] == "123456")
        #expect(v["h1port"] == "3017" && v["h1fp"] == "sha256:abc" && v["api"] == "1")

        let without = try #require(MobileConnectionInfo.qrPayload(host: "192.168.1.20", port: 3006, pin: "123456",
                                                                  hostApiPort: 3017, hostApiFingerprint: nil))
        let plain = try #require(URLComponents(string: without)?.queryItems)
        #expect(plain.map(\.name) == ["ip", "port", "pin"])
    }

    @Test("Reset security identity revokes every v1 device, keeps v2 devices, and mints a new identity")
    func reset() throws {
        let store = tempStore()
        _ = store.issueToken(deviceId: MobilePairedDeviceStore.hostApiDevicePrefix + "one", name: "web", scopes: ["host"])
        _ = store.issueToken(deviceId: "phone-v2", name: "iPhone")
        let before = try HostApiV1Identity.loadOrCreate(hostName: "test").fingerprint
        let manager = MobileControlManager(pairedDeviceStore: store, hostApiAudit: tempAudit())

        manager.resetHostApiIdentity()

        #expect(store.all.map(\.id) == ["phone-v2"])
        #expect(manager.pairedDevices.map(\.id) == ["phone-v2"])
        #expect(manager.hostApiIdentityFailure == nil)
        let after = try HostApiV1Identity.loadOrCreate(hostName: "test")
        #expect(after.created, "the old identity was deleted")
        #expect(after.fingerprint != before)
    }

    @Test("a corrupt identity is never regenerated by loading, only by Reset")
    func corruptNeedsReset() throws {
        _ = KeychainStore.backend.write(account: HostApiV1Identity.account, service: "com.llmide.macapp", data: Data("junk".utf8))
        #expect(throws: HostApiV1Identity.Failure.corrupt) { try HostApiV1Identity.loadOrCreate(hostName: "test") }
        #expect(throws: HostApiV1Identity.Failure.corrupt) { try HostApiV1Identity.loadOrCreate(hostName: "test") }
        MobileControlManager(pairedDeviceStore: tempStore(), hostApiAudit: tempAudit()).resetHostApiIdentity()
        #expect(try HostApiV1Identity.loadOrCreate(hostName: "test").created)
    }

    @Test("the v1 device filter picks h1- ids only")
    func filter() {
        let store = tempStore()
        _ = store.issueToken(deviceId: "h1-a", name: "a")
        _ = store.issueToken(deviceId: "v2", name: "b")
        #expect(MobileControlManager.hostApiDeviceIds(store.all) == ["h1-a"])
    }

    @Test("an account wipe revokes the v1 devices along with the identity")
    func credentialsRevoked() {
        let store = tempStore()
        _ = store.issueToken(deviceId: "h1-a", name: "a", scopes: ["host"])
        let manager = MobileControlManager(pairedDeviceStore: store, hostApiAudit: tempAudit())
        manager.accountCredentialsRevoked()
        #expect(MobileControlManager.hostApiDeviceIds(store.all).isEmpty)
    }
}
